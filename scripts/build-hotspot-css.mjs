// ---------------------------------------------------------------------------
// Dev-only tool. Reads prototype/hotspots.json (written by
// capture-sections.mjs) and emits prototype/css/hotspots.generated.css —
// per-breakpoint percentage position rules for every [data-hotspot]
// element. Numbers are generated, never hand-typed: rerun this whenever
// capture-sections.mjs produces a new hotspots.json.
//
// Usage:  node scripts/build-hotspot-css.mjs
// ---------------------------------------------------------------------------
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const HOTSPOTS_PATH = path.join(ROOT, 'prototype', 'hotspots.json');
const OUT_PATH = path.join(ROOT, 'prototype', 'css', 'hotspots.generated.css');

// Must match the <source media="…"> breakpoints in prototype/index.html.
const MEDIA = {
  mobile: null, // base rule, no media query
  tablet: '(min-width: 768px) and (max-width: 1024px)',
  desktop: '(min-width: 1025px)',
};

function rule(sectionKey, hotspotName, box) {
  const selector = `[data-hotspot="${sectionKey}.${hotspotName}"]`;
  return `${selector} { left: ${box.left}%; top: ${box.top}%; width: ${box.width}%; height: ${box.height}%; }`;
}

async function run() {
  const hotspots = JSON.parse(await readFile(HOTSPOTS_PATH, 'utf8'));

  const lines = [
    '/* AUTO-GENERATED by scripts/build-hotspot-css.mjs from prototype/hotspots.json.',
    '   Do not hand-edit — rerun the script instead. */',
    '',
  ];

  // Base (mobile) rules first, unwrapped.
  for (const [sectionKey, byLayout] of Object.entries(hotspots)) {
    const box = byLayout.mobile;
    if (!box) continue;
    for (const [name, coords] of Object.entries(box)) {
      lines.push(rule(sectionKey, name, coords));
    }
  }

  // Then tablet/desktop overrides, each in their own media block.
  for (const [layoutName, media] of Object.entries(MEDIA)) {
    if (!media) continue;
    const blockLines = [];
    for (const [sectionKey, byLayout] of Object.entries(hotspots)) {
      const box = byLayout[layoutName];
      if (!box) continue;
      for (const [name, coords] of Object.entries(box)) {
        blockLines.push('  ' + rule(sectionKey, name, coords));
      }
    }
    if (blockLines.length) {
      lines.push('', `@media ${media} {`, ...blockLines, '}');
    }
  }

  await writeFile(OUT_PATH, lines.join('\n') + '\n');
  console.log(`Wrote ${path.relative(ROOT, OUT_PATH)}`);
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
